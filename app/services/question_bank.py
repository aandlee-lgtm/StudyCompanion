"""Creating questions (with fingerprints, mappings and labels) and topping up the
template-generated Mathematics bank so LEARNING subtopics never run dry."""
from __future__ import annotations

from datetime import date
from functools import lru_cache

from sqlalchemy import func, select
from sqlalchemy.orm import Session

from app.models import LearningPlanItem, Question, QuestionExposure, QuestionMapping, Source, Subject, SyllabusOutcome
from app.models.common import APPROVAL_APPROVED, DIRECT, ORIGIN_GENERATED
from app.services import maths_templates
from app.services.fingerprint import NEAR_DUPLICATE, fingerprint, similarity

MINUTES_PER_MARK = {"MATHS": 1.8, "ENGLISH": 1.75, "LEGAL": 1.8}


def estimate_minutes(subject_code: str, marks: int, question_type: str) -> float:
    if question_type == "mcq":
        return 1.5
    per = MINUTES_PER_MARK.get(subject_code, 1.8)
    return round(per * marks + 0.5, 1)


def get_or_create_source(db: Session, title: str, **kw) -> Source:
    src = db.execute(select(Source).where(Source.title == title)).scalar_one_or_none()
    if src is None:
        src = Source(title=title, **kw)
        db.add(src)
        db.flush()
    return src


def template_source(db: Session) -> Source:
    maths = db.execute(select(Subject).where(Subject.code == "MATHS")).scalar_one()
    return get_or_create_source(
        db, "HSC Companion — syllabus-aligned question templates (Mathematics Advanced)",
        organisation="HSC Companion (generated)", subject_id=maths.id, source_type="generated", tier=4, official=False,
        notes="Parametrised questions generated by the app. Answers and worked solutions computed with SymPy. Not past HSC questions.",
    )


def outcome_for_topic(db: Session, topic_id: int | None) -> int | None:
    if topic_id is None:
        return None
    return db.execute(select(SyllabusOutcome.id).where(SyllabusOutcome.topic_id == topic_id).limit(1)).scalar_one_or_none()


def find_duplicate(db: Session, subject_id: int, text: str, check_similar: bool = False) -> Question | None:
    fp = fingerprint(text)
    q = db.execute(select(Question).where(Question.fingerprint == fp, Question.subject_id == subject_id)).scalars().first()
    if q or not check_similar:
        return q
    for other in db.execute(select(Question).where(Question.subject_id == subject_id)).scalars():
        if similarity(other.question_text, text) >= NEAR_DUPLICATE:
            return other
    return None


def create_question(db: Session, *, subject_code: str, mapping_reason: str, mapped_by: str = "seed",
                    relevance: str = DIRECT, confidence: float = 1.0, auto_approve: bool = True, **fields) -> Question:
    subj = db.execute(select(Subject).where(Subject.code == subject_code)).scalar_one()
    dup = find_duplicate(db, subj.id, fields["question_text"])
    if dup is not None:
        return dup
    fields.setdefault("estimated_minutes", estimate_minutes(subject_code, fields.get("marks", 1), fields.get("question_type", "short_answer")))
    if fields.get("syllabus_outcome_id") is None:
        fields["syllabus_outcome_id"] = outcome_for_topic(db, fields.get("topic_id"))
    q = Question(subject_id=subj.id, fingerprint=fingerprint(fields["question_text"]), relevance_status=relevance,
                 relevance_score=1.0 if relevance == DIRECT else 0.5, mapping_confidence=confidence, **fields)
    if auto_approve:
        q.approval_status, q.approved = APPROVAL_APPROVED, True
    db.add(q)
    db.flush()
    db.add(QuestionMapping(
        question_id=q.id, mapped_topic_id=q.topic_id, outcome_id=q.syllabus_outcome_id,
        relevance_classification=relevance, relevance_score=q.relevance_score, mapping_confidence=confidence,
        mapping_reason=mapping_reason, mapped_by=mapped_by, review_status="approved" if auto_approve else "pending",
    ))
    db.flush()
    return q


def generate_from_template(db: Session, item: LearningPlanItem, difficulty: int, seed: int) -> Question | None:
    g = maths_templates.generate(item.code, seed, difficulty)
    if g is None:
        return None
    subj_id = item.subject_id
    if find_duplicate(db, subj_id, g.text) is not None:
        return None
    src = template_source(db)
    focus = item.topic.name if item.topic else "Mathematics Advanced"
    return create_question(
        db, subject_code="MATHS", source_id=src.id, question_text=g.text, marks=g.marks, difficulty=g.difficulty,
        question_type=g.question_type, directive_verb=g.directive_verb, topic_id=item.topic_id, plan_item_id=item.id,
        historical_or_generated=ORIGIN_GENERATED, answer=g.answer, solution=g.solution(),
        estimated_minutes=maths_templates.minutes_for(g.marks), source_exam=template_tag(item.code, difficulty),
        mapping_reason=f"Generated from the app's {item.code} template, written for the 2027 focus area '{focus}'.",
    )


def template_tag(code: str, level: int) -> str:
    return f"Template {code} L{level}"


@lru_cache(maxsize=None)
def template_levels(code: str) -> dict[int, tuple[int, ...]]:
    """Requested level -> the difficulties the template ACTUALLY produces (probed on a few seeds;
    pure, so it never depends on the database). Used to top up by real difficulty and to report
    templates that cannot produce a level (selection-08)."""
    out: dict[int, tuple[int, ...]] = {}
    for d in (1, 2, 3):
        produced = set()
        for seed in range(4):
            try:
                g = maths_templates.generate(code, 10_000 + seed, d)
            except Exception:  # a template error must never break session generation
                g = None
            if g is not None:
                produced.add(g.difficulty)
        out[d] = tuple(sorted(produced))
    return out


def template_gaps(code: str) -> list[int]:
    """Difficulty levels this item's template cannot produce."""
    if code not in maths_templates.TEMPLATES:
        return []
    made = {x for v in template_levels(code).values() for x in v}
    return [d for d in (1, 2, 3) if d not in made]


def unseen_count(db: Session, item: LearningPlanItem, level: int) -> int:
    """Unseen generated template questions on ``item`` whose ACTUAL difficulty is ``level``."""
    seen = select(QuestionExposure.question_id)
    return db.execute(
        select(func.count(Question.id)).where(
            Question.plan_item_id == item.id, Question.source_exam.like(f"Template {item.code} L%"), Question.difficulty == level,
            Question.approved.is_(True), Question.id.not_in(seen),
        )
    ).scalar_one()


def ensure_template_questions(db: Session, item: LearningPlanItem, per_difficulty: int = 2) -> int:
    """Top up unseen template questions for ``item`` so each difficulty level the template can
    really produce has ``per_difficulty`` unseen questions. Returns how many were created."""
    if item.code not in maths_templates.TEMPLATES:
        return 0
    created = 0
    levels = template_levels(item.code)
    for d in (1, 2, 3):
        if d not in levels.get(d, ()):
            continue  # the template cannot produce this level when asked for it (see template_gaps)
        need = per_difficulty - unseen_count(db, item, d)
        if need <= 0:
            continue
        total = db.execute(select(func.count(Question.id)).where(Question.plan_item_id == item.id)).scalar_one()
        seed, tries = total * 7 + d, 0
        while need > 0 and tries < 25:
            q = generate_from_template(db, item, d, seed)
            seed += 1
            tries += 1
            if q is not None:
                created += 1
                if q.difficulty == d:
                    need -= 1
    return created


