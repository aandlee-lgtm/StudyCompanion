"""A realistic multi-week study history for analytics tests (owner: analytics).

``build_history`` drives the real daily-session engine and ``assessment.submit`` day by day:
sessions are generated by the selection engine, answered with uneven but deliberate
performance (strong on some plan items, weak on others, weaker on challenging questions,
an occasional skip and a few lucky guesses), some weekdays are missed, one session is left
partly done, and the Maths learning plan advances every week. It only uses public functions
(``sessions.get_or_create_today``, ``sessions.maybe_complete``, ``assessment.submit``) so it
keeps working while selection internals change."""
from __future__ import annotations

import random
from dataclasses import dataclass, field
from datetime import date, timedelta

from sqlalchemy import select

from app.models import LearningPlanItem, Question
from app.services import assessment, clock, plan, sessions

START = date(2026, 10, 12)  # Monday


@dataclass
class History:
    start: date
    end: date
    missed: list[date] = field(default_factory=list)
    partial: list[date] = field(default_factory=list)
    completed: list[date] = field(default_factory=list)
    answered: int = 0


# Plan-item performance profile: probability of a fully correct answer (Maths/MCQ) or the
# quality of a written answer. Items not listed use DEFAULT_SKILL.
STRONG_ITEMS = {"Y11-CALC": 0.95, "1A": 0.9, "1B": 0.9, "1C": 0.85, "Y11-FUNC": 0.85, "LS-CRIME": 0.75}
WEAK_ITEMS = {"Y11-PROB": 0.25, "Y11-TRIG": 0.4, "1E": 0.35, "1F": 0.35, "LS-HR": 0.3}
DEFAULT_SKILL = 0.62


def _skill(code: str | None) -> float:
    if code and code.startswith("LS-") and code.count("-") >= 2:  # Legal sub-areas share their topic's skill
        code = "-".join(code.split("-")[:2])
    if code in STRONG_ITEMS:
        return STRONG_ITEMS[code]
    if code in WEAK_ITEMS:
        return WEAK_ITEMS[code]
    return DEFAULT_SKILL


def _wrong_answer(q: Question) -> str:
    ces = (q.solution or {}).get("common_errors") or []
    for ce in ces:
        if "," not in str(ce.get("answer", "")):
            return str(ce["answer"])
    if (q.answer or {}).get("type") == "mcq":
        right = q.answer["value"].upper()
        return next(x for x in "ABCD" if x != right)
    return "999999"


def _right_answer(q: Question) -> str:
    a = q.answer or {}
    if a.get("type") == "set":
        return ", ".join(a["values"])
    return str(a.get("value", ""))


def answer_question(db, sq, rng: random.Random, item_code: str | None, day_index: int, skip: bool = False):
    q = sq.question
    skill = _skill(item_code)
    # challenging questions are harder; the student improves slowly over the weeks
    skill = max(0.05, min(0.98, skill - 0.25 * (q.difficulty - 2) + 0.004 * day_index))
    est = max(1.0, q.estimated_minutes)
    t = int(60 * est * rng.uniform(0.8, 1.7 if skill < 0.5 else 1.2))
    if skip:
        return assessment.submit(db, q, "", sq=sq, time_seconds=int(t / 3), skipped=True)
    good = rng.random() < skill
    confidence = "confident" if good else rng.choice(["unsure", "confident", "guess"])
    if good and rng.random() < 0.12:
        confidence = "guess"  # a lucky guess
    if q.answer is not None:
        resp = _right_answer(q) if good else _wrong_answer(q)
        return assessment.submit(db, q, resp, sq=sq, confidence=confidence, time_seconds=t,
                                 working="Working shown." if q.subject_id and not good else None)
    if good:
        resp = q.model_answer or "A detailed analytical response that 'quotes' the text, explains how it shapes meaning and evaluates its effect."
    else:
        resp = rng.choice(["The writer uses a metaphor. It is about memory.", "The law is effective because it is fair.",
                           "It shows the idea. The technique is used."])
    return assessment.submit(db, q, resp, sq=sq, confidence=confidence, time_seconds=t)


def build_history(db, weeks: int = 6, start: date = START, seed: int = 7, missed_days: tuple[int, ...] = (8, 17, 18),
                  partial_days: tuple[int, ...] = (12,), advance_every: int = 5) -> History:
    """Simulate ``weeks`` weeks of weekdays. ``missed_days`` / ``partial_days`` are indexes of
    study days (0-based) that are skipped entirely / left with 4 answers."""
    rng = random.Random(seed)
    one_a = db.execute(select(LearningPlanItem).where(LearningPlanItem.code == "1A")).scalar_one()
    plan.start_from(db, one_a.id)
    db.commit()
    items = {i.id: i.code for i in db.execute(select(LearningPlanItem)).scalars()}
    h = History(start=start, end=start)
    d, idx = start, 0
    end = start + timedelta(weeks=weeks)
    while d < end:
        if d.weekday() >= 5:
            d += timedelta(days=1)
            continue
        clock.set_today(d)
        if idx and idx % advance_every == 0:
            plan.advance(db, "MATHS")
        if idx in missed_days:
            h.missed.append(d)
        else:
            sess = sessions.get_or_create_today(db)
            limit = 4 if idx in partial_days else len(sess.questions)
            total_t = 0
            for n, sq in enumerate(sess.questions[:limit]):
                skip = rng.random() < 0.05
                a = answer_question(db, sq, rng, items.get(sq.question.plan_item_id), idx, skip=skip)
                total_t += a.time_seconds
                h.answered += 1
            sess.elapsed_seconds = total_t + 120
            if sess.status == "generated":
                sess.status = "in_progress"
            if sessions.maybe_complete(db, sess):
                h.completed.append(d)
            else:
                h.partial.append(d)
            db.commit()
        h.end = d
        idx += 1
        d += timedelta(days=1)
    # the morning after: record missed days as the app would when it is next opened
    clock.set_today(d)
    sessions.record_missed(db, d, lookback_days=7 * weeks + 7)
    db.commit()
    return h
